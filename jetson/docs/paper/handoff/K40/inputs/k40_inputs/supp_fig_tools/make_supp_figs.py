# ---------------------- 7. latency vs decision value, and deadlines (Jetson tables)
def latency():
    rows = table_body("tab:latency_baselines")
    pts = []
    for r in rows:
        nm = name(r[0])
        pts.append((nm, num(r[1]), num(r[2]), num(r[3]), num(r[4]), num(r[5]), num(r[6])))
    # whole frame + comp.: latency from tab:latency, G on the full test splits (C1 column of tab:uniform)
    lat = {name(r[0]): (num(r[2]), num(r[3]), num(r[5]), num(r[6])) for r in table_body("tab:latency")}
    uni = {}
    for r in table_body("tab:uniform"):
        if r[0] in ("512", "960", "1280", "Native"):
            uni[r[0]] = (num(r[10]), num(r[4]))        # nuScenes C1, Argoverse 2 C1
    wf = []
    for side, key in (("512", "u512 + comp."), ("960", "u960 + comp."), ("1280", "u1280 + comp."), ("Native", "Native + comp.")):
        l = lat[key]
        wf.append((key, uni[side][0], l[0], l[1], uni[side][1], l[2], l[3]))
    # one row per method: dot at the mean latency, bar to the 95th percentile, decision value on the right;
    # black: decision value at least that of DESP on the dataset, grey: lower
