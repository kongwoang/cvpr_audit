# --------------------------------------------------- 5. coverage (tab:coverage)
def coverage():
    rows = table_body("tab:coverage")
    labels, ypos, y = [], [], 0.0
    groups = []
    prev_group = None
    group_of = lambda s: ("all" if s.startswith("All") else "range" if s.startswith("Range")
                          else "lat" if s.startswith("Lateral") else "close" if s.startswith("Closing")
                          else "draft" if "draft" in s else "class")
    for r in rows:
        g = group_of(r[0])
        if prev_group is not None and g != prev_group:
            y += 0.6
            groups.append(y - 0.8)
        prev_group = g
        labels.append(clean(r[0]).replace("$<", "$<").replace("(AHD: vehicles)", "(AHD: vehicles)"))
        ypos.append(y)
        y += 1.0
    col = {"nusc": (1, 2), "av2": (4, 5), "ahd": (7, 8)}
    marks = {"nusc": ("square*", "square"), "av2": ("*", "o"), "ahd": ("triangle*", "triangle")}
    off = {"nusc": -0.22, "av2": 0.0, "ahd": 0.22}
    out = ["\\begin{tikzpicture}",
           "\\begin{axis}[width=0.66\\linewidth, height=0.80\\linewidth, xmin=0.6, xmax=1.02,",
           "  ymin=-0.8, ymax=%.1f, y dir=reverse, ytick={%s}," % (ypos[-1] + 0.8, ",".join("%.1f" % p for p in ypos)),
           "  yticklabels={%s}," % ",".join("{%s}" % l for l in labels),
           "  xtick={0.6,0.7,0.8,0.9,1.0}, tick label style={font=\\scriptsize}, label style={font=\\small},",
           "  xlabel={coverage of the decisive object}, xmajorgrids, grid style={gray!20},",
           "  legend style={font=\\scriptsize, at={(0.02,0.02)}, anchor=south west, draw=gray!50}, legend cell align=left]"]
    for gy in groups:
        out.append("\\draw[gray!40] (axis cs:0.6,%.2f) -- (axis cs:1.02,%.2f);" % (gy, gy))
    for ds in ("nusc", "av2", "ahd"):
        cc, nc = col[ds]
        big = [(num(r[cc]), p) for r, p in zip(rows, ypos) if num(r[cc]) is not None and num(r[nc]) >= 30]
        small = [(num(r[cc]), p) for r, p in zip(rows, ypos) if num(r[cc]) is not None and num(r[nc]) < 30]
        out.append("\\addplot[%s, only marks, mark=%s, mark size=1.9pt] coordinates {%s};"
                   % (DS[ds][1], marks[ds][0], " ".join("(%.2f,%.2f)" % (c, p + off[ds]) for c, p in big)))
        out.append("\\addlegendentry{%s}" % DS[ds][0])
        if small:
            out.append("\\addplot[%s, only marks, mark=%s, mark size=1.9pt, thick, forget plot] coordinates {%s};"
                       % (DS[ds][1], marks[ds][1], " ".join("(%.2f,%.2f)" % (c, p + off[ds]) for c, p in small)))
    out += ["\\end{axis}", "\\end{tikzpicture}"]
    write("fig_coverage.tex", "\n".join(out) + "\n")


