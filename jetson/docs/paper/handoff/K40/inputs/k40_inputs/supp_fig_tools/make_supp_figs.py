# ----------------------------------------------------------------- parsing
def table_body(label):
    """Rows (lists of cells) of the tabular that carries \\label{label}."""
    i = TEX.index("\\label{%s}" % label)
    beg = TEX.rfind("\\begin{table", 0, i)
    end = TEX.index("\\end{table", i)
    body = TEX[beg:end]
    body = body[body.index("\\midrule"):body.rindex("\\bottomrule")]
    rows = []
    for line in body.splitlines():
        line = line.strip()
        if "&" not in line or not line.endswith("\\\\"):
            continue
        line = line[:-2]
        rows.append([c.strip() for c in line.split("&")])
    return rows


def clean(cell):
    for a, b in [("\\oursrow", ""), ("$-$", "-"), ("\\%", ""), ("{,}", ""),
                 ("$^{\\dagger}$", ""), ("$^{\\ast}$", ""), ("$^{\\S}$", "")]:
        cell = cell.replace(a, b)
    cell = re.sub(r"\\(best|textbf|second|underline)\{(.*)\}", r"\2", cell)
    return cell.strip()


def num(cell):
    c = clean(cell)
    if c in ("\\na", "--", ""):
        return None
    return float(c)


def ci(cell):
    c = clean(cell)
    m = re.search(r"\\ci\{([^{}]*)\}\{([^{}]*)\}", c)
    if not m:
        return None
    return float(m.group(1).replace("$", "")), float(m.group(2).replace("$", ""))


def name(cell):
    c = clean(cell)
    c = re.sub(r"~?\\cite\{[^}]*\}", "", c)
    c = c.replace("\\method", "DESP").replace("\\textbf{", "").replace("}", "")
    return c.strip()


